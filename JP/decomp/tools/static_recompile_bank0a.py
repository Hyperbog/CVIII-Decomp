#!/usr/bin/env python3
"""Statically lower EVERY 0538 bank $0A decoded instruction into C++ calls.

This explicitly preserves separate classes: 2162 historically audited code bytes,
2910 structural CANDIDATE code bytes, and the remaining data/unknown bytes.
No raw ROM bytes are embedded in generated C++: only literal instruction operands.
PCs outside the selected classes fail closed; it is not a full-game recompilation.
"""
from __future__ import annotations
import argparse,hashlib,json,re
from collections import Counter
from pathlib import Path
from audit_nmi_fixed_scheduler_banked import OPS

JP_SHA='958a4b5e95e80acb2c71a43e9ef2e91444f3d097ae9d4eeb747f0dac8abe7a28'
BANK_SHA='1460df577d44e114c64fdf34a8837629765f3f6a93d45796fdf81e5ffacb5ed8'
CPU_START=0x8000;CPU_END=0xc000
REGEX=re.compile(r'^\s*;\s*(AUDITED 6502|STATIC 6502 CANDIDATE \(UNPROVED\)|.*?) (?:starts|from)\s+\$[0-9a-fA-F]+')

def source_cases(source:str, bank:bytes)->tuple[list[dict],dict]:
    if len(bank)!=16384 or hashlib.sha256(bank).hexdigest()!=BANK_SHA:
        raise ValueError('bank0A is not the authenticated original 16KiB image')
    pos=None;category='not_code';out=[];seen=bytearray(16384)
    for lineno,line in enumerate(source.splitlines(),1):
        if line.startswith('; AUDITED 6502 '):category='audited'
        elif line.startswith('; STATIC 6502 CANDIDATE (UNPROVED) '):category='candidate'
        elif line.startswith(';') and ((' starts $' in line) or (' from $' in line)):
            category='not_code'
        raw=line.split(';',1)[0].strip().lower()
        if not raw or raw.startswith('.equ '):continue
        if raw.startswith('.org '):pos=int(raw[5:].lstrip('$'),16);continue
        if raw.endswith(':'):continue
        if pos is None:raise ValueError('instruction before .org')
        parts=raw.split(None,1);m=parts[0]
        if m=='.byte':size=len(parts[1].split(','))
        elif m=='.word':size=len(parts[1].split(','))*2
        else:
            if category not in ('audited','candidate'):
                raise ValueError(f'6502 instruction in unclassified part at {pos:04X}')
            opcode=bank[pos-CPU_START]
            if opcode not in OPS:raise ValueError(f'unsupported original opcode {opcode:02X} at {pos:04X}')
            mn,mode,size=OPS[opcode]
            if mn.lower()!=m:raise ValueError(f'source/opcode drift at {pos:04X}: {m} vs {mn}')
            operand=bank[pos+1-CPU_START:pos+size-CPU_START]
            arg=(0 if size==1 else operand[0] if size==2 else int.from_bytes(operand,'little'))
            if mode=='rel':arg=(pos+2+(arg if arg<128 else arg-256))&65535
            if mode not in ('imp','acc','imm','zp','zpx','zpy','abs','absx','absy','indx','indy','ind','rel'):
                raise ValueError(f'unsupported address mode: {mode}')
            out.append(dict(pc=pos,category=category,mnemonic=mn,mode=mode,arg=arg,next=pos+size,opcode=opcode,size=size))
        if pos<CPU_START or pos+size>CPU_END:raise ValueError('source crosses physical bank')
        if any(seen[pos+i-CPU_START] for i in range(size)):
            raise ValueError(f'overlapping source position at {pos:04X}')
        for i in range(size):seen[pos+i-CPU_START]=1
        pos+=size
    if not all(seen):raise ValueError('source incomplete across whole 16KiB bank')
    counts=Counter()
    for row in out:counts[row['category']+'_bytes']+=row['size'];counts[row['category']+'_instructions']+=1
    if (counts['audited_bytes'],counts['candidate_bytes'])!=(2162,2910):
        raise ValueError(f'unexpected historical code-byte counts: {counts}')
    return out,dict(counts)

def generate(rows:list[dict])->str:
    lines=[
      '// GENERATED by JP/decomp/tools/static_recompile_bank0a.py from authenticated ROM.',
      '// These are native compiled 6502 semantic operations, NOT recovered C game logic.',
      '// The candidate branch is disabled by default; all other addresses fail closed.',
      '#include "static_6502.hpp"',
      'namespace jpstatic {',
      'StepResult compiled_step(Cpu& cpu,bool allow_conditional) {',
      '  switch(cpu.pc) {',
    ]
    for row in rows:
        pc,mn,mode,arg,nxt=row['pc'],row['mnemonic'],row['mode'],row['arg'],row['next']
        lines.append(f'    case 0x{pc:04X}: {{')
        if row['category']=='candidate':lines.append('      if(!allow_conditional) return StepResult::candidate_blocked;')
        lines.append(f'      cpu.exec<Op::{mn},Mode::{mode}>(0x{arg:04X},0x{nxt:04X});')
        lines.append('      return StepResult::executed; }')
    lines.extend(['    default:return StepResult::unresolved;', '  }','}','}'])
    return '\n'.join(lines)+'\n'

def main()->None:
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--rom',type=Path,required=True)
    p.add_argument('--source',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args()
    data=args.rom.read_bytes()
    if len(data)!=393232 or hashlib.sha256(data).hexdigest()!=JP_SHA:
        raise ValueError('original Japanese iNES identity mismatch')
    bank=data[16+10*16384:16+11*16384]
    src=args.source.read_text(encoding='utf-8')
    rows,counts=source_cases(src,bank)
    args.output.mkdir(parents=True,exist_ok=True)
    (args.output/'bank0a_compiled.cpp').write_text(generate(rows),encoding='utf-8')
    from importlib import import_module
    # Reassemble full original bank via project original-source assembler.
    from build_whole_cart_recomp_0529 import assemble
    if assemble(src,0x8000,0x4000)!=bank:raise ValueError('source is not the original bank')
    manifest={'schema':'JP-static-native-lift-bank0A/v1','bank_sha256':BANK_SHA,
      'original_rom_sha256':JP_SHA,'raw_bank_bytes':16384,'instruction_sites':len(rows),
      **counts,'unknown_and_data_bytes':16384-counts['audited_bytes']-counts['candidate_bytes'],
      'candidate_code_certified':False,'native_frame_parity':False,
      'description':'Explicitly compiled, CPU-semantics lowering of already classified 6502 instruction sites. Other addresses fail closed.'}
    (args.output/'bank0a_native_manifest.json').write_text(json.dumps(manifest,sort_keys=True,indent=2)+'\n')
    print(json.dumps(manifest,sort_keys=True))
if __name__=='__main__':main()
