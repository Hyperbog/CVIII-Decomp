#!/usr/bin/env python3
"""JP0736 — Compare a NEW retail native CYCFRAME run with owner MesenCE.

No ROM, screenshots, CPU RAM, input, original CHR, or derived graphics are
written to the repository. Prints aggregate checks and optional color-class
comparison. Input native log is generated by NESRecomp's --frame-log-at mesen.
Color-class comparison (requires Pillow) maps each 9-bit NES color class to
a consistent RGB value using ALL selected archival reference snapshots.
No single-frame arbitrary recoloring is allowed.
"""
from __future__ import annotations
from collections import Counter, defaultdict
from io import BytesIO
from pathlib import Path
import argparse
import hashlib
import json
import struct
import zipfile

ROM_SHA256="958a4b5e95e80acb2c71a43e9ef2e91444f3d097ae9d4eeb747f0dac8abe7a28"
HEADER=struct.Struct("<9I")

def native_records(path:Path):
    with path.open("rb") as f:
        if f.read(8)!=b"CYCFRAME" or f.read(4)!=struct.pack("<I",2):
            raise ValueError("expected NESRecomp CYCFRAME v2")
        while (header:=f.read(HEADER.size)):
            if len(header)!=HEADER.size:raise ValueError("truncated CYCFRAME")
            frame,low,high,*sizes=HEADER.unpack(header)
            palette=f.read(32)
            oam=f.read(256)
            blobs=[f.read(size) for size in sizes]
            if len(palette)!=32 or len(oam)!=256 or any(
                len(data)!=size for data,size in zip(blobs,sizes)):
                raise ValueError("truncated CYCFRAME payload")
            if sizes[0]!=2048 or sizes[1] not in (2048,4096) or sizes[4]!=122880:
                raise ValueError("wrong native RAM, CIRAM or color-index layout")
            yield frame,(high<<32)|low,blobs[0],blobs[1],palette,blobs[4]

def load_archive(path:Path):
    with zipfile.ZipFile(path) as archive:
        names=archive.namelist()
        ramfile=next(n for n in names if n.endswith("-ram.tsv"))
        ppufile=next(n for n in names if n.endswith("-ppu.tsv"))
        ramrows=[r.split("\t") for r in archive.read(ramfile).decode().splitlines()
                 if r.startswith("R\t")]
        ppurows=[r.split("\t") for r in archive.read(ppufile).decode().splitlines()
                 if r.startswith("S\t")]
        if len(ramrows)!=len(ppurows):raise ValueError("Mesen R/PPU count mismatch")
        scenes={}
        for r,p in zip(ramrows,ppurows):
            if r[1]!=p[1] or r[2]!=p[2] or r[3]!=p[3]:
                raise ValueError("Mesen R/PPU timeline mismatch")
            frame=int(r[2])
            scene=dict(frame=frame,cycle=int(r[3]),ram=bytes.fromhex(r[5]),
                       nametable=bytes.fromhex(p[13]),
                       palette=bytes.fromhex(p[7]),image_name=p[12])
            if len(scene["ram"])!=2048 or len(scene["nametable"])!=4096:
                raise ValueError("original R/PPU bytes incomplete")
            scenes[frame]=scene
        return scenes,{n:archive.read(n) for n in names if n.endswith("-raw.png")}

def compare(rom_path:Path,mesen_zip:Path,cycframe:Path,max_frame:int):
    if hashlib.sha256(rom_path.read_bytes()).hexdigest()!=ROM_SHA256:
        raise ValueError("incorrect original Japanese ROM identity")
    scenes,images=load_archive(mesen_zip)
    results=[]
    color_hist=defaultdict(Counter)
    try:
        from PIL import Image
    except ImportError:
        Image=None
    for frame,cycle,ram,ciram,palette,color in native_records(cycframe):
        if frame>max_frame:break
        if frame not in scenes:continue
        ref=scenes[frame]
        mismatch=sum(a!=b for a,b in zip(ram,ref["ram"]))
        # Physical VRC6 CIRAM is 2KB; the Mesen export is 4KB logical
        # nametable space. Evaluate both pages per logical 1KB block, without
        # pretending this proves the original mapper selection register.
        nt_mismatch=[]
        for k in range(4):
            original=ref["nametable"][k*1024:(k+1)*1024]
            possible=[sum(a!=b for a,b in zip(original,ciram[i*1024:(i+1)*1024]))
                      for i in range(len(ciram)//1024)]
            nt_mismatch.append(min(possible))
        pal_mismatch=sum(a!=b for a,b in zip(palette,ref["palette"]))
        if Image is not None:
            original_rgb=Image.open(BytesIO(images[ref["image_name"]])).convert("RGB").tobytes()
            pairs=Counter()
            for i in range(256*240):
                idx=color[2*i]|(color[2*i+1]<<8)
                px=original_rgb[i*3:i*3+3]
                pairs[(idx,px)]+=1
                color_hist[idx][px]+=1
        else:pairs=None
        results.append(dict(frame=frame,cycle_delta=cycle-ref["cycle"],
                            ram_differences=mismatch,
                            nametable_differences=nt_mismatch,
                            palette_differences=pal_mismatch,
                            pairs=pairs))
    if not results:raise ValueError("no Mesen frames covered by native log")
    fixed_colors={k:v.most_common(1)[0][0] for k,v in color_hist.items()}
    for row in results:
        pairs=row.pop("pairs")
        row["pixel_class_differences"]=(
            sum(n for (idx,rgb),n in pairs.items() if fixed_colors[idx]!=rgb)
            if pairs is not None else None)
    return {
        "source_sha256_verified":True,
        "matched_checkpoints":len(results),
        "all_probed_nametable_pages_match":all(
            sum(row["nametable_differences"])==0 for row in results),
        "max_ram_byte_differences":max(row["ram_differences"] for row in results),
        "max_abs_cpu_cycle_delta":max(abs(row["cycle_delta"]) for row in results),
        "pixel_class_exact_checkpoints":sum(
            row["pixel_class_differences"]==0 for row in results)
            if fixed_colors else None,
        "pixel_class_mapping": "fixed across all sampled frames" if fixed_colors else "not available",
        "samples":results,
    }

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rom",type=Path,required=True)
    parser.add_argument("--mesen-zip",type=Path,required=True)
    parser.add_argument("--native-frame-log",type=Path,required=True)
    parser.add_argument("--max-frame",type=int,default=999999)
    args=parser.parse_args()
    print(json.dumps(compare(args.rom,args.mesen_zip,
                             args.native_frame_log,args.max_frame),indent=2))

if __name__=="__main__":
    main()
