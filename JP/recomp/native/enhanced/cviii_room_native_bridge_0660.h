#ifndef CVIII_ROOM_NATIVE_BRIDGE_0660_H
#define CVIII_ROOM_NATIVE_BRIDGE_0660_H
#include "cviii_room_stream_0659.h"
#include <stddef.h>
#include <stdint.h>
/* A non-mutating observer of the authentic Japanese PRG0A:$B7F7 routine.
 * All guest execution stays in the 6502; this is NOT a cycle-certified HLE. */
#define CVIII_0660_ENTRY_PC 0xB7F7u
#define CVIII_0660_BANK4 0x2Bu /* 16-KiB raw PRG0A, $B000-$BFFF */
#define CVIII_0660_PAYLOAD_SIZE 185u
#define CVIII_0660_PACK_SIZE (64u + CVIII_0660_PAYLOAD_SIZE)
typedef struct {
    uint8_t bank0a[16384], bank0e[16384];
    CviiiRoomStream0659 predicted;
    uint64_t entered_cycles;
    uint64_t observed_entries, passed, mismatched, partial, skipped;
    uint16_t return_pc;
    uint8_t entry_s, entry_i, entry_d, selector;
    uint8_t actual_mapper[CVIII_0659_MAPPER_MAX], actual_writes;
    uint8_t ready, active, trace_at_entry, event_overflow;
} CviiiRoomNativeBridge0660;
/* Import authenticated-source, owner-local 249-byte pack generated by
 * build_room_native_bridge_0660.py. On rejection no state is changed. */
int cviii_bridge0660_load(CviiiRoomNativeBridge0660 *bridge, const char *path);
/* Call on the actual original $B7F7 LDA $07A0 final operand read.
 * Caller has authenticated current 4-KiB PRG bank and entry opcode.
 * Does not alter guest RAM or registers. */
int cviii_bridge0660_begin(CviiiRoomNativeBridge0660 *b,
    const uint8_t *ram, size_t ram_size, uint8_t s,
    uint8_t overflow, uint8_t irq_disable, uint8_t decimal,
    uint64_t cycles, int trace_available);
/* Observe a real CPU write to mapper port $8000 (only if tracing enabled). */
void cviii_bridge0660_mapper_write(CviiiRoomNativeBridge0660 *b, uint8_t value);
/* 1=RAM,registers,flags and mapper-write values agree;
 * 2=RAM/registers agree, mapper write order NOT observable;
 * -1=divergence; 0=not the expected final RTS.
 * No return value authorizes replacing original 6502 execution: exact cycle,
 * open-bus and interrupt behavior remains to be proven. */
int cviii_bridge0660_rts(CviiiRoomNativeBridge0660 *b,
    const uint8_t *ram, size_t ram_size, uint16_t pc,
    uint8_t a, uint8_t x, uint8_t y, uint8_t s,
    uint8_t c, uint8_t z, uint8_t n, uint8_t v,
    uint8_t i, uint8_t d, unsigned mapped_bank4);
void cviii_bridge0660_reset(CviiiRoomNativeBridge0660 *b);
#endif